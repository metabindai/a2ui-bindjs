/**
 * Derives the basic catalog's shape from the vendored v1.0 schema.
 *
 * Which properties of a component hold references to other components is not uniform:
 * `Row.children` is a list, `Card.child` is a single id, `Modal` uses two named props
 * (`trigger`, `content`), and `Tabs` nests ids inside an array of objects (`tabs[].child`).
 * Hand-listing those is how the first pass got Tabs and Modal wrong, so the list is
 * generated from `catalogs/basic/catalog.json` instead.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const catalogPath = join(here, '..', '..', 'vendor', 'spec', 'v1_0', 'catalogs', 'basic', 'catalog.json')
const outputPath = join(here, '..', 'src', 'engine', 'basicCatalog.generated.ts')

const catalog = JSON.parse(readFileSync(catalogPath, 'utf8'))

const isRefTo = (node, name) => typeof node?.$ref === 'string' && node.$ref.endsWith(`/${name}`)

/** Merges the `allOf` branches a component schema is written as. */
function propertiesOf(schema) {
    const merged = {}

    for (const branch of schema.allOf ?? [schema]) {
        Object.assign(merged, branch.properties ?? {})
    }

    return merged
}

function slotsFor(schema) {
    const slots = []

    for (const [prop, definition] of Object.entries(propertiesOf(schema))) {
        if (isRefTo(definition, 'ChildList')) {
            slots.push({ prop, kind: 'list' })
            continue
        }

        if (isRefTo(definition, 'Child')) {
            slots.push({ prop, kind: 'single' })
            continue
        }

        // An array of objects, one of whose properties is a child reference (Tabs).
        if (definition.type === 'array' && definition.items?.properties) {
            for (const [key, inner] of Object.entries(definition.items.properties)) {
                if (isRefTo(inner, 'Child')) {
                    slots.push({ prop, kind: 'objectList', childKey: key })
                }
            }
        }
    }

    return slots
}

const components = Object.keys(catalog.components ?? {}).sort()
const slots = {}

for (const name of components) {
    const found = slotsFor(catalog.components[name])

    if (found.length > 0) {
        slots[name] = found
    }
}

const functions = Object.keys(catalog.functions ?? {}).sort()

const output = `// GENERATED by scripts/build-catalog-slots.mjs — do not edit.
// Source of truth: vendor/spec/v1_0/catalogs/basic/catalog.json (A2UI v1.0, Apache-2.0)

import type { ChildSlot } from './types.js'

/** Every component type the v1.0 basic catalog defines. */
export const BASIC_CATALOG_COMPONENTS: readonly string[] = ${JSON.stringify(components)}

/** Functions the basic catalog declares. Used to check our registry against the spec. */
export const BASIC_CATALOG_FUNCTIONS: readonly string[] = ${JSON.stringify(functions)}

/**
 * Properties that hold child references, per component type.
 * \`children\` / \`child\` become positional children; anything else becomes a named
 * prop carrying the built component(s).
 */
export const BASIC_CATALOG_SLOTS: Record<string, ChildSlot[]> = ${JSON.stringify(slots, null, 4)}
`

writeFileSync(outputPath, output)
console.log(`build-catalog-slots: ${components.length} components, ${Object.keys(slots).length} with child slots → ${outputPath}`)
